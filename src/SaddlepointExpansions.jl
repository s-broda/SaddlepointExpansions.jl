"""
    SaddlepointExpansions

Saddlepoint expansions of any order for tail probabilities and densities of random vectors,
from the cumulant generating function alone. The expansions are those of Broda and Kan,
"Uniform saddlepoint expansions for multivariate tail probabilities": the orthant probability
``P(X ≥ x)`` (Theorem 1, with the inclusion-exclusion of Section 3.3 for saddlepoints with
negative components), the density (Theorem 3) and the density and distribution function of a
ratio (Theorem 4 and Corollaries), in any dimension, together with the univariate expansions of
Daniels and of Hauschildt and Robinson as the case ``d = 1``.

The user supplies the cumulant generating function ``K`` as an ordinary Julia function of a vector,
wrapped in a [`CGF`](@ref). All derivatives of ``K`` that the expansions need are generated by
Taylor-mode automatic differentiation (TaylorSeries.jl), directly in the whitened coordinates in
which the terms are evaluated, so that no derivative formulas have to be written by hand. The
main functions are [`tailprob`](@ref), [`density`](@ref), [`ratio_density`](@ref),
[`ratio_tailprob`](@ref), [`saddlepoint`](@ref) and [`derivatives`](@ref). Ready-made cumulant
generating functions for common models are in the library ([`normal_cgf`](@ref),
[`gamma_cgf`](@ref), [`ncx2_cgf`](@ref), [`quadratic_forms_cgf`](@ref),
[`wishart_diag_cgf`](@ref), [`exponential_sums_cgf`](@ref), [`common_component_cgf`](@ref)),
and cumulant generating functions can be transformed ([`reflect`](@ref), [`marginal`](@ref),
[`linear_combination`](@ref), [`sample_mean`](@ref)).

Everything is generic in the floating-point type: pass `BigFloat` arguments inside
`setprecision` for variable precision. The lower-level functions `spa_uni`, `spa_bi`, `spa_mv`,
`spa_orthant`, ... take the derivatives of ``K`` from a user-supplied function `Kfun(nu, t)`
instead, for cumulant generating functions whose derivatives are available in closed form.
"""
module SaddlepointExpansions

using LinearAlgebra
using SpecialFunctions: erfc, erfcx, erfcinv, loggamma, gamma_inc, beta_inc
using QuadGK: quadgk
using TaylorSeries: TaylorSeries, JetSpace, TaylorN, variables, getcoeff, constant_term

# cumulant generating functions and the high-level interface
export CGF, derivatives, saddlepoint, tailprob, density, ratio_density, ratio_tailprob,
       reflect, marginal, linear_combination, sample_mean, shift
# library of cumulant generating functions
export normal_cgf, gamma_cgf, ncx2_cgf, quadratic_forms_cgf, wishart_diag_cgf,
       exponential_sums_cgf, common_component_cgf
# derivative interface (Kfun(nu, t)) and the engine
export spa_uni, spa_ratio_pdf, spa_bi, spa_bi_at, spa_orthant2, spa_mv, spa_tri, spa_mv_at,
       spa_orthant, spa_saddle, qf_Kmulti, orthant2, orthant3,
       ncx2_Kder, bqfcc_Kfun, mvcc_Kfun, lin_exp_Kfun, wishdiag_kfun
# ready-made univariate distributions and exact values
export ncx2_spa, ncf_spa, dncf_spa, dncf_saddle,
       ncx2_exact, gamma_exact, dncf_exact_dp, bqfcc_exact, mvcc_exact
# first-order approximations of the literature, for comparisons
export kl_bivar, wang_bivar

include("util.jl")
include("univariate.jl")
include("bivariate.jl")
include("orthant.jl")
include("quadforms.jl")
include("distributions.jl")
include("exact.jl")
include("multivariate.jl")
include("kfuns.jl")
include("cgf.jl")
include("api.jl")
include("cgfs.jl")

end
