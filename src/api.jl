# The high-level interface: saddlepoint, tail probabilities, densities and ratios from a CGF.

"""
    saddlepoint(K::CGF, x; tau0=nothing) -> (tau, info)

The saddlepoint ``K'(τ) = x`` (Newton's method with backtracking on the convex objective
``K(τ) - τ'x``; see [`spa_saddle`](@ref) for the stopping rules and the contents of `info`). An
error is raised if the iteration does not converge. For `d = 1`, `x` may be a scalar, and `tau` is
then a scalar.
"""
function saddlepoint(K::CGF, x::AbstractVector; tau0=nothing)
    length(x) == K.d || throw(ArgumentError("saddlepoint: x must have length $(K.d)"))
    return spa_saddle(_kfun(K, 2), x, tau0)
end
function saddlepoint(K::CGF, x::Real; tau0=nothing)
    K.d == 1 || throw(ArgumentError("saddlepoint: a scalar x needs a univariate cumulant generating function"))
    tau, info = saddlepoint(K, [x]; tau0=(tau0 === nothing ? nothing : [tau0]))
    return tau[1], info
end

function _checkorder(name, order)
    order >= 1 || throw(ArgumentError("$name: order must be a positive integer"))
end

# signs of the components for the requested corner
function _signs(name, d, lower, signs)
    if signs === nothing
        return lower ? fill(-1, d) : ones(Int, d)
    end
    length(signs) == d || throw(ArgumentError("$name: signs must have length $d"))
    all(s -> s == 1 || s == -1, signs) || throw(ArgumentError("$name: signs must be ±1"))
    return collect(Int, signs)
end

"""
    tailprob(K::CGF, x; order=3, lower=false, signs=nothing, kwargs...)
        -> (; F, tau, status, info)

Saddlepoint expansions of orders `1:order` of the orthant probability ``P(X ≥ x)`` (componentwise)
for the random vector with cumulant generating function `K`, at the point `x` (a vector of
length `d`; a scalar when `d = 1`). `F[M]` is the expansion of order `M`, which keeps the terms of
orders ``n^{-m/2}``, ``m ≤ 2M-1``, of the expansion in powers of ``n^{-1/2}``, and has relative
error ``O(n^{-M})`` uniformly for saddlepoints in compact subsets of the closed positive orthant
(Theorem 1 of the paper; the "``n``" is absorbed in `K`). `F[1]` is the first-order approximation
of Kolassa (2003) in two or more dimensions and that of Hauschildt and Robinson in one.

* `lower = true` gives ``P(X ≤ x)``, and `signs` (a vector of ``±1``) any mixed corner, e.g.
  `signs = [1, -1]` for ``P(X_1 ≥ x_1, X_2 ≤ x_2)``; the components are reflected
  ([`reflect`](@ref)) and the result is an upper orthant probability of the reflected vector.
* When the saddlepoint has negative components the expansion is applied through the
  inclusion-exclusion identity of Section 3.3 of the paper (lower-dimensional marginal terms with
  their own saddlepoints), which keeps the relative error bound.
* `tau` is the saddlepoint of `K` at `x`. `status` is `"ok"` or a description of a problem in the
  evaluation (see [`spa_bi`](@ref) and [`spa_mv`](@ref)); `info` is the full result of the
  underlying routine, with the cancellation indicators, quadrature checks and saddlepoint
  diagnostics.

The derivatives of `K` are generated by Taylor-mode differentiation at the saddlepoint, directly
in the whitened coordinates in which the terms are evaluated. The computation runs in the
floating-point type of `x`; with `BigFloat` arguments (inside `setprecision`) everything, the
differentiation included, is done in that precision. In three dimensions the integrals ``I(ν)``
are computed by Gauss quadrature and in four or more by randomized quasi-Monte Carlo
(`info.err` is then a standard error); see [`spa_mv`](@ref) for the keywords (`nG`, `nqmc`, ...),
which are passed on, and [`spa_orthant2`](@ref) for those of the bivariate case (`nG`,
`logscale` for probabilities below the double-precision range, ...).
"""
function tailprob(K::CGF, x::AbstractVector; order::Integer=3, lower::Bool=false, signs=nothing,
                  kwargs...)
    _checkorder("tailprob", order)
    d = K.d
    length(x) == d || throw(ArgumentError("tailprob: x must have length $d"))
    all(isfinite, x) || throw(ArgumentError("tailprob: x must be finite"))
    sg = _signs("tailprob", d, lower, signs)
    Kr = all(==(1), sg) ? K : reflect(K, sg)
    T = float(eltype(x))
    xr = T.(sg .* collect(x))
    maxdeg = 2order + 1
    Kf = _kfun(Kr, maxdeg)
    if d == 1
        s, sinfo = spa_saddle(Kf, xr, nothing)
        Kd = [Kf((k,), s) for k in 0:maxdeg]
        all(isfinite, Kd) || error("tailprob: the saddlepoint is outside the domain of K")
        r = spa_uni(Kd, s[1], xr[1], order)
        return (; F=r.upp, tau=sg .* s, status="ok", info=(; r..., saddle=sinfo))
    elseif d == 2
        r = spa_orthant2(Kf, xr, order; Kwhite=_kwhite(Kr, maxdeg), kwargs...)
        return (; F=r.Fup, tau=sg .* r.tau, status=r.status, info=r)
    else
        r = spa_orthant(Kf, xr, order; Kwhite=_kwhite(Kr, maxdeg), kwargs...)
        return (; F=r.Fup, tau=sg .* r.tau, status="ok", info=r)
    end
end
function tailprob(K::CGF, x::Real; kwargs...)
    K.d == 1 || throw(ArgumentError("tailprob: a scalar x needs a univariate cumulant generating function"))
    r = tailprob(K, [x]; kwargs...)
    return (; F=r.F, tau=r.tau[1], status=r.status, info=r.info)
end

"""
    density(K::CGF, x; order=3, kwargs...) -> (; f, tau, status, info)

Saddlepoint expansions of orders `1:order` of the density at `x` of the random vector with
cumulant generating function `K`: `f[M]` keeps the terms ``m ≤ M-1`` of the expansion in powers
of ``n^{-1}`` and has relative error ``O(n^{-M})`` (Theorem 3 of the paper; Daniels's expansion
when `d = 1`). The expansion is a finite sum of Hermite polynomials and needs no integration, in
any dimension. `tau` is the saddlepoint, `status` is `"ok"` or a warning about the evaluation,
and `info` the result of the underlying routine.

In three or more dimensions the terms of high orders can cancel by many orders of magnitude; the
cancellation indicator is monitored and the computation is repeated automatically in `BigFloat`
when it exceeds ``10^6`` (`refine = true`, the default; see [`spa_mv`](@ref)). Keywords are
passed on to [`spa_bi`](@ref) (`d = 2`) and [`spa_mv`](@ref) (`d ≥ 3`).
"""
function density(K::CGF, x::AbstractVector; order::Integer=3, kwargs...)
    _checkorder("density", order)
    d = K.d
    length(x) == d || throw(ArgumentError("density: x must have length $d"))
    all(isfinite, x) || throw(ArgumentError("density: x must be finite"))
    T = float(eltype(x))
    xx = T.(collect(x))
    maxdeg = 2order + 1
    Kf = _kfun(K, maxdeg)
    if d == 1
        s, sinfo = spa_saddle(Kf, xx, nothing)
        Kd = [Kf((k,), s) for k in 0:maxdeg]
        all(isfinite, Kd) || error("density: the saddlepoint is outside the domain of K")
        r = spa_uni(Kd, s[1], xx[1], order)
        return (; f=r.pdf, tau=s, status="ok", info=(; r..., saddle=sinfo))
    elseif d == 2
        r = spa_bi(Kf, xx, order; Kwhite=_kwhite(K, maxdeg), kwargs...)
        st = occursin("coefficients inaccurate", r.status) ? "coefficients inaccurate" : "ok"
        return (; f=r.pdf, tau=r.tau, status=st, info=r)
    else
        r = spa_mv(Kf, xx, order; method=:none, Kwhite=_kwhite(K, maxdeg), kwargs...)
        st = occursin("coefficients inaccurate", r.info.status) ? "coefficients inaccurate" :
             occursin("refinement failed", r.info.status) ? "refinement failed" : "ok"
        return (; f=r.pdf, tau=r.tau, status=st, info=r)
    end
end
function density(K::CGF, x::Real; kwargs...)
    K.d == 1 || throw(ArgumentError("density: a scalar x needs a univariate cumulant generating function"))
    r = density(K, [x]; kwargs...)
    return (; f=r.f, tau=r.tau[1], status=r.status, info=r.info)
end

# cumulant generating function of W = X_1 - r X_2 (the sign of X_2 is that of the denominator)
function _ratio_cgf(K::CGF, r::Real)
    K.d == 2 || throw(ArgumentError("ratio: K must be the joint cumulant generating function of the numerator and the denominator (d = 2)"))
    f = s -> K.K([s[1], -r*s[1]])
    dom = K.domain === nothing ? nothing : (s -> K.domain([s[1], -r*s[1]]))
    return CGF(f, 1; domain=dom)
end

"""
    ratio_density(K::CGF, r; order=3) -> (; f, shat, status, info)

Saddlepoint expansions of orders `1:order` of the density at `r` of the ratio ``R = X_1/X_2`` of
the two components of a vector with cumulant generating function `K` (`d = 2`), the denominator
being positive, ``X_2 > 0``: the Rice (Laplace-type) expansion of
``f_R(r) = (2πi)^{-1} ∫ \\exp\\{K_W(s)\\}\\,g(s)\\,ds``, ``K_W(s) = K(s, -rs)``,
``g(s) = ∂_2K(s, -rs)``, through the saddlepoint ``K_W'(\\hat s) = 0`` (Theorem 4 and its
corollary in the paper); `f[M]` has relative error ``O(n^{-M})``. The derivatives of ``K_W`` and
of the amplitude ``g`` are generated by Taylor-mode differentiation of `K` at ``(\\hat s, -r\\hat s)``.
"""
function ratio_density(K::CGF, r::Real; order::Integer=3)
    _checkorder("ratio_density", order)
    KW = _ratio_cgf(K, r)
    T = float(typeof(r))
    s, sinfo = spa_saddle(_kfun(KW, 2), [zero(T)], nothing)
    sh = s[1]
    N = 2order + 1
    sp = _space(2, N)
    v = variables(T, sp)
    P = try
        K.K([sh + v[1], -r*(sh + v[1]) + v[2]])
    catch err
        err isa DomainError && error("ratio_density: the saddlepoint is outside the domain of K")
        rethrow()
    end
    isfinite(constant_term(P)) || error("ratio_density: the saddlepoint is outside the domain of K")
    KWd = [_coef(T, P, (k, 0)) for k in 0:2order]
    gd = [_coef(T, P, (l, 1)) for l in 0:2order-2]
    f = spa_ratio_pdf(KWd, gd, sh, order)
    return (; f, shat=sh, status="ok", info=(; KWd, gd, saddle=sinfo))
end

"""
    ratio_tailprob(K::CGF, r; order=3, lower=false) -> (; F, shat, status, info)

Saddlepoint expansions of orders `1:order` of ``P(X_1/X_2 ≥ r)`` (or ``P(X_1/X_2 ≤ r)`` with
`lower = true`) for a positive denominator ``X_2 > 0``: the probability equals
``P(X_1 - rX_2 ≥ 0)``, and the univariate expansion of [`tailprob`](@ref) is applied to
``W = X_1 - rX_2`` at ``0`` (Theorem 4 of the paper). `shat` is the saddlepoint of ``K_W``.
"""
function ratio_tailprob(K::CGF, r::Real; order::Integer=3, lower::Bool=false)
    _checkorder("ratio_tailprob", order)
    KW = _ratio_cgf(K, r)
    T = float(typeof(r))
    t = tailprob(KW, zero(T); order, lower)
    return (; F=t.F, shat=t.tau, status=t.status, info=t.info)
end
