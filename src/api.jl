# The high-level interface: saddlepoint, tail probabilities, densities and ratios from a CGF.

"""
    saddlepoint(K::CGF, x; tau0=nothing) -> (tau, info)

The saddlepoint ``K'(τ) = x`` (Newton's method with backtracking on the convex objective
``K(τ) - τ'x``; see [`spa_saddle`](@ref) for the stopping rules and the contents of `info`). An
error is raised if the iteration does not converge. For `d = 1`, `x` may be a scalar, and `tau` is
then a scalar.
"""
function saddlepoint(K::CGF, x::AbstractVector; tau0=nothing)
    length(x) == K.d || throw(ArgumentError("saddlepoint: x must have length $(K.d)"))
    return spa_saddle(_kfun(K, 2), x, tau0)
end
function saddlepoint(K::CGF, x::Real; tau0=nothing)
    K.d == 1 || throw(ArgumentError("saddlepoint: a scalar x needs a univariate cumulant generating function"))
    tau, info = saddlepoint(K, [x]; tau0=(tau0 === nothing ? nothing : [tau0]))
    return tau[1], info
end

function _checkorder(name, order)
    order >= 1 || throw(ArgumentError("$name: order must be a positive integer"))
end

# signs of the components for the requested corner
function _signs(name, d, lower, signs)
    if signs === nothing
        return lower ? fill(-1, d) : ones(Int, d)
    end
    length(signs) == d || throw(ArgumentError("$name: signs must have length $d"))
    all(s -> s == 1 || s == -1, signs) || throw(ArgumentError("$name: signs must be ±1"))
    return collect(Int, signs)
end

"""
    tailprob(K::CGF, x; order=3, lower=false, signs=nothing, lattice=false, sinh=:saddle, kwargs...)
        -> (; F, tau, status, info)

Saddlepoint expansions of orders `1:order` of the orthant probability ``P(X ≥ x)`` (componentwise)
for the random vector with cumulant generating function `K`, at the point `x` (a vector of
length `d`; a scalar when `d = 1`). `F[M]` is the expansion of order `M`, which keeps the terms of
orders ``n^{-m/2}``, ``m ≤ 2M-1``, of the expansion in powers of ``n^{-1/2}``, and has relative
error ``O(n^{-M})`` uniformly for saddlepoints in compact subsets of the closed positive orthant
(Theorem 1 of the paper; the "``n``" is absorbed in `K`). `F[1]` is the first-order approximation
of Kolassa (2003) in two or more dimensions and that of Hauschildt and Robinson in one.

* `lower = true` gives ``P(X ≤ x)``, and `signs` (a vector of ``±1``) any mixed corner, e.g.
  `signs = [1, -1]` for ``P(X_1 ≥ x_1, X_2 ≤ x_2)``; the components are reflected
  ([`reflect`](@ref)) and the result is an upper orthant probability of the reflected vector.
* When the saddlepoint has negative components the expansion is applied through the
  inclusion-exclusion identity of Section 3.3 of the paper (lower-dimensional marginal terms with
  their own saddlepoints), which keeps the relative error bound.
* `tau` is the saddlepoint of `K` at `x`. `status` is `"ok"` or a description of a problem in the
  evaluation (see [`spa_bi`](@ref) and [`spa_mv`](@ref)); `info` is the full result of the
  underlying routine, with the cancellation indicators, quadrature checks and saddlepoint
  diagnostics.
* `lattice = true`: ``X = S`` is integer-valued and so is `x` ``= k``; `F` is then
  ``P(S ≥ k)`` with the continuity correction and the amplitude
  ``\\prod_j s_j/\\{2\\sinh(s_j/2)\\}``, by Theorem 3 of Broda and Kan, "Conditional saddlepoint
  expansions of arbitrary order", with no conditioning components (the computation is that of
  [`conditional_tailprob`](@ref) with `A = 1:d`, and the numbers are the same): the saddlepoint is
  taken at ``k - 1/2`` in every component, and `sinh = :saddle` (default) expands the amplitude
  about the saddlepoint, `sinh = :origin` about the origin, keeping ``s^{2M-2}`` at order ``M``
  (Kolassa 2003). In one dimension `F[1]`, with the terms of orders ``n^{0}`` and ``n^{-1/2}``,
  has the relative error ``O(n^{-1})`` of the continuity-corrected approximations of Daniels
  (1987). `lower = true` gives ``P(S ≤ k)``; saddlepoints with negative components are handled
  by the inclusion-exclusion with ``P(S_j ≤ k_j - 1) = P(-S_j ≥ -k_j + 1)``, the components not
  kept in a term being marginalized. `info` holds `Fp` (the expansions with the terms up to
  ``n^{-j/2}``), `kappa` and `err`. Where the continuity-corrected point is not inside the
  convex hull of the support (as for ``P(S ≥ 0)`` of a count) there is no saddlepoint and an
  error is raised.

The derivatives of `K` are generated by Taylor-mode differentiation at the saddlepoint, directly
in the whitened coordinates in which the terms are evaluated. The computation runs in the
floating-point type of `x`; with `BigFloat` arguments (inside `setprecision`) everything, the
differentiation included, is done in that precision. In three dimensions the integrals ``I(ν)``
are computed by Gauss quadrature and in four or more by randomized quasi-Monte Carlo
(`info.err` is then a standard error); see [`spa_mv`](@ref) for the keywords (`nG`, `nqmc`, ...),
which are passed on, and [`spa_orthant2`](@ref) for those of the bivariate case (`nG`,
`logscale` for probabilities below the double-precision range, ...).
"""
function tailprob(K::CGF, x::AbstractVector; order::Integer=3, lower::Bool=false, signs=nothing,
                  lattice::Bool=false, sinh::Symbol=:saddle, kwargs...)
    _checkorder("tailprob", order)
    d = K.d
    length(x) == d || throw(ArgumentError("tailprob: x must have length $d"))
    all(isfinite, x) || throw(ArgumentError("tailprob: x must be finite"))
    sg = _signs("tailprob", d, lower, signs)
    Kr = all(==(1), sg) ? K : reflect(K, sg)
    T = float(eltype(x))
    xr = T.(sg .* collect(x))
    maxdeg = 2order + 1
    Kf = _kfun(Kr, maxdeg)
    if lattice
        # Theorem 3 of the conditional paper with B empty: the same computation as
        # conditional_tailprob(K, x, 1:d; lattice=true)
        nG = get(kwargs, :nG, 64)
        r = _spa_cond(Kf, _kwhite(Kr, maxdeg), xr, collect(1:d), order; density=false, lattice=true,
                      sinh, nG)
        tau = sg .* r.tau
        return (; F=r.P, tau=(d == 1 && x isa Real ? tau[1] : tau), status=r.status,
                info=(; Fp=r.Pp, kappa=r.kappaP, err=r.err, nG))
    end
    if d == 1
        s, sinfo = spa_saddle(Kf, xr, nothing)
        Kd = [Kf((k,), s) for k in 0:maxdeg]
        all(isfinite, Kd) || error("tailprob: the saddlepoint is outside the domain of K")
        r = spa_uni(Kd, s[1], xr[1], order)
        return (; F=r.upp, tau=sg .* s, status="ok", info=(; r..., saddle=sinfo))
    elseif d == 2
        r = spa_orthant2(Kf, xr, order; Kwhite=_kwhite(Kr, maxdeg), kwargs...)
        return (; F=r.Fup, tau=sg .* r.tau, status=r.status, info=r)
    else
        r = spa_orthant(Kf, xr, order; Kwhite=_kwhite(Kr, maxdeg), kwargs...)
        return (; F=r.Fup, tau=sg .* r.tau, status="ok", info=r)
    end
end
function tailprob(K::CGF, x::Real; kwargs...)
    K.d == 1 || throw(ArgumentError("tailprob: a scalar x needs a univariate cumulant generating function"))
    r = tailprob(K, [x]; kwargs...)
    return (; F=r.F, tau=r.tau[1], status=r.status, info=r.info)
end

"""
    density(K::CGF, x; order=3, lattice=false, normalize=false, kwargs...) -> (; f, tau, status, info)

Saddlepoint expansions of orders `1:order` of the density at `x` of the random vector with
cumulant generating function `K`: `f[M]` keeps the terms ``m ≤ M-1`` of the expansion in powers
of ``n^{-1}`` and has relative error ``O(n^{-M})`` (Theorem 3 of the paper; Daniels's expansion
when `d = 1`). The expansion is a finite sum of Hermite polynomials and needs no integration, in
any dimension. `tau` is the saddlepoint, `status` is `"ok"` or a warning about the evaluation,
and `info` the result of the underlying routine.

In three or more dimensions the terms of high orders can cancel by many orders of magnitude; the
cancellation indicator is monitored and the computation is repeated automatically in `BigFloat`
when it exceeds ``10^6`` (`refine = true`, the default; see [`spa_mv`](@ref)). Keywords are
passed on to [`spa_bi`](@ref) (`d = 2`) and [`spa_mv`](@ref) (`d ≥ 3`).

With `lattice = true` (integer-valued ``S``, integer `x` ``= k``) `f` is the probability
``P(S = k)``: the same expansion at ``k``, the saddlepoint approximation of Daniels (1987) at order
one (Theorem 3 of Broda and Kan, "Conditional saddlepoint expansions of arbitrary order", with no
conditioning components); it is computed as [`conditional_density`](@ref) with `A = 1:d`, in
whitened coordinates in any dimension, and the numbers are the same.

`normalize = true` divides the expansion of every order ``M`` by its total mass
``c_M = ∫ f_M(x)\\,dx`` (Daniels's normalization), returned in `info.mass`; the integral is computed
in saddlepoint space, ``x = K'(s)``, ``dx = \\det K''(s)\\,ds``, so that the saddlepoint is known at
every quadrature node and no saddlepoint equation is solved there: by adaptive Gauss-Kronrod
quadrature (QuadGK) over the domain of ``K``, nested over the coordinates in more than one
dimension (each inner line centred at the regression of the inner coordinates on the outer ones
under ``K''(0)``), the tails truncated where the leading term has fallen by ``e^{-50}`` relative to
its value at the centre. The masses do not depend on `x`: pass `normalize = r.info.mass` from an
earlier call to reuse them. One quadrature costs a few hundred evaluations of the expansion in one
dimension and the square of that in two; in more dimensions it is expensive. For the normal
distribution ``c_M = 1``; for the gamma distribution with shape ``a``,
``c_1 = Γ(a)e^aa^{1/2-a}/\\sqrt{2π}``, and the normalized expansion of every order is exact.
"""
function density(K::CGF, x::AbstractVector; order::Integer=3, lattice::Bool=false, normalize=false,
                 kwargs...)
    if normalize !== false
        lattice && throw(ArgumentError("density: normalize is for continuous variables"))
        T = float(eltype(x))
        mass = normalize === true ? _density_mass(K, order, T) : T.(collect(normalize))
        length(mass) >= order || throw(ArgumentError("density: normalize must be true or a vector of $order masses"))
        r = density(K, x; order, kwargs...)
        return (; f=r.f ./ mass[1:order], tau=r.tau, status=r.status, info=(; r.info..., mass=mass[1:order]))
    end
    _checkorder("density", order)
    d = K.d
    length(x) == d || throw(ArgumentError("density: x must have length $d"))
    all(isfinite, x) || throw(ArgumentError("density: x must be finite"))
    T = float(eltype(x))
    xx = T.(collect(x))
    maxdeg = 2order + 1
    Kf = _kfun(K, maxdeg)
    if lattice
        # P(S = k): the density expansion at k (Theorem 3 of the conditional paper with B empty),
        # by the computation of conditional_density(K, x, 1:d; lattice=true)
        r = _spa_cond(Kf, _kwhite(K, maxdeg), xx, collect(1:d), order; tail=false)
        return (; f=r.f, tau=r.tauf, status=r.status, info=(; kappa=r.kappaf))
    end
    if d == 1
        s, sinfo = spa_saddle(Kf, xx, nothing)
        Kd = [Kf((k,), s) for k in 0:maxdeg]
        all(isfinite, Kd) || error("density: the saddlepoint is outside the domain of K")
        r = spa_uni(Kd, s[1], xx[1], order)
        return (; f=r.pdf, tau=s, status="ok", info=(; r..., saddle=sinfo))
    elseif d == 2
        r = spa_bi(Kf, xx, order; Kwhite=_kwhite(K, maxdeg), kwargs...)
        st = occursin("coefficients inaccurate", r.status) ? "coefficients inaccurate" : "ok"
        return (; f=r.pdf, tau=r.tau, status=st, info=r)
    else
        r = spa_mv(Kf, xx, order; method=:none, Kwhite=_kwhite(K, maxdeg), kwargs...)
        st = occursin("coefficients inaccurate", r.info.status) ? "coefficients inaccurate" :
             occursin("refinement failed", r.info.status) ? "refinement failed" : "ok"
        return (; f=r.pdf, tau=r.tau, status=st, info=r)
    end
end
function density(K::CGF, x::Real; kwargs...)
    K.d == 1 || throw(ArgumentError("density: a scalar x needs a univariate cumulant generating function"))
    r = density(K, [x]; kwargs...)
    return (; f=r.f, tau=r.tau[1], status=r.status, info=r.info)
end

# cumulant generating function of W = X_1 - r X_2 (the sign of X_2 is that of the denominator)
function _ratio_cgf(K::CGF, r::Real)
    K.d == 2 || throw(ArgumentError("ratio: K must be the joint cumulant generating function of the numerator and the denominator (d = 2)"))
    return linear_combination(K, reshape([1.0, -float(r)], 2, 1))
end

"""
    ratio_density(K::CGF, r; order=3, general=false, normalize=false) -> (; f, shat, status, info)

Saddlepoint expansions of orders `1:order` of the joint density at `r` of the vector of ratios
``R = (X_1/Y_1, …, X_d/Y_d)``, ``d`` = `length(r)`, with positive denominators ``Y_j > 0``. `K` is
the cumulant generating function of ``(X_1, …, X_d, Y_1, …, Y_d)`` (dimension ``2d``) or, for a
common denominator ``Y``, of ``(X_1, …, X_d, Y)`` (dimension ``d + 1``). For a scalar `r` (one
ratio, `K` of dimension two) the expansion is the Rice (Laplace-type) expansion of
``f_R(r) = (2πi)^{-1}∫\\exp\\{K_W(s)\\}\\,g(s)\\,ds``, ``K_W(s) = K(s, -rs)``,
``g(s) = ∂_2K(s, -rs)``, through the saddlepoint ``K_W'(\\hat s) = 0`` (Theorem 4 and its
corollary in the paper); for a vector it is Theorem 4 with the amplitude expansion of Corollary 1,
in whitened coordinates, with every Taylor coefficient taken from one Taylor polynomial of
``K(s, -r∘s + τ)`` in ``(u, τ)``. `f[M]` has relative error ``O(n^{-M})``; `shat` is the
saddlepoint of ``K_W``. `general = true` uses the vector code also for ``d = 1`` (for checks).

For one ratio, `normalize = true` divides the expansion of every order by its total mass, returned
in `info.mass` (pass it back as `normalize` to reuse it): the integral over ``r`` is computed in
saddlepoint space, over the saddlepoint ``\\hat s`` along the curve ``sK_1 + tK_2 = 0``,
``t = -r\\hat s``, on which ``r = K_1/K_2`` (see [`ratio_quantile`](@ref)), with
``dr = (dr/d\\hat s)\\,d\\hat s``, by adaptive Gauss-Kronrod quadrature, the tails truncated where the
leading term has fallen by ``e^{-50}``; each node gives its ``t`` by a one-dimensional Newton
iteration on the curve, and no saddlepoint equation in ``r`` is solved.
"""
function ratio_density(K::CGF, r::Real; order::Integer=3, general::Bool=false, normalize=false)
    if normalize !== false
        T = float(typeof(r))
        mass = normalize === true ? _ratio_mass(_ratio_cgf2(K, 1, "ratio_density"), order, T) : T.(collect(normalize))
        length(mass) >= order || throw(ArgumentError("ratio_density: normalize must be true or a vector of $order masses"))
        rr = ratio_density(K, r; order, general)
        return (; f=rr.f ./ mass[1:order], shat=rr.shat, status=rr.status, info=(; rr.info..., mass=mass[1:order]))
    end
    _checkorder("ratio_density", order)
    if general
        f, info = _ratio_mv(_ratio_cgf2(K, 1, "ratio_density"), [r], order)
        return (; f, shat=info.shat[1], status="ok", info)
    end
    KW = _ratio_cgf(K, r)
    T = float(typeof(r))
    s, sinfo = spa_saddle(_kfun(KW, 2), [zero(T)], nothing)
    sh = s[1]
    N = 2order + 1
    P = _taylor(K, [sh, -r*sh], N, [1.0 0.0; -float(r) 1.0])   # K(ŝ + v1, -r(ŝ + v1) + v2)
    P === nothing && error("ratio_density: the saddlepoint is outside the domain of K")
    KWd = [_coef(T, P, (k, 0)) for k in 0:2order]
    gd = [_coef(T, P, (l, 1)) for l in 0:2order-2]
    f = spa_ratio_pdf(KWd, gd, sh, order)
    return (; f, shat=sh, status="ok", info=(; KWd, gd, saddle=sinfo))
end
function ratio_density(K::CGF, r::AbstractVector; order::Integer=3, general::Bool=false)
    _checkorder("ratio_density", order)
    d = length(r)
    d == 1 && !general && return ratio_density(_ratio_cgf2(K, 1, "ratio_density"), r[1]; order)
    f, info = _ratio_mv(_ratio_cgf2(K, d, "ratio_density"), r, order)
    return (; f, shat=info.shat, status="ok", info)
end

"""
    ratio_tailprob(K::CGF, r; order=3, lower=false, signs=nothing, kwargs...) -> (; F, shat, status, info)

Saddlepoint expansions of orders `1:order` of ``P(R ≥ r)`` for the vector of ratios
``R = (X_1/Y_1, …, X_d/Y_d)`` with positive denominators (`K` as in [`ratio_density`](@ref); a
scalar `r` for one ratio): the probability equals ``P(W ≥ 0)`` for ``W = X - r∘Y``, and
[`tailprob`](@ref) is applied to ``W`` at ``0`` (Theorem 4 of the paper; the univariate expansion
for one ratio). `lower = true` gives ``P(R ≤ r)``, `signs` a mixed corner, and the other keywords
are passed to `tailprob`. `shat` is the saddlepoint of ``K_W``.
"""
function ratio_tailprob(K::CGF, r::Real; order::Integer=3, lower::Bool=false, kwargs...)
    _checkorder("ratio_tailprob", order)
    KW = _ratio_cgf(K, r)
    T = float(typeof(r))
    t = tailprob(KW, zero(T); order, lower, kwargs...)
    return (; F=t.F, shat=t.tau, status=t.status, info=t.info)
end
function ratio_tailprob(K::CGF, r::AbstractVector; order::Integer=3, lower::Bool=false, signs=nothing, kwargs...)
    _checkorder("ratio_tailprob", order)
    d = length(r)
    d == 1 && return ratio_tailprob(_ratio_cgf2(K, 1, "ratio_tailprob"), r[1]; order, lower, kwargs...)
    K2 = _ratio_cgf2(K, d, "ratio_tailprob")
    rr = float.(collect(r))
    KW = linear_combination(K2, vcat(Matrix(1.0I, d, d), -Matrix(Diagonal(rr))))
    t = tailprob(KW, zeros(eltype(rr), d); order, lower, signs, kwargs...)
    return (; F=t.F, shat=t.tau, status=t.status, info=t.info)
end
