# Univariate expansions: Daniels (density) and Hauschildt-Robinson (distribution function),
# Corollaries 2 and 3 of the paper.

"""
    spa_uni(Kd, shat, xbar, order; uthr=2.5) -> (; pdf, cdf, upp, kappa)

Saddlepoint approximations of orders `1:order` of the density and the distribution function of
a scalar variable `X` at `xbar`, from the derivatives of its cumulant generating function at the
saddlepoint: `Kd[k+1]` = ``K^{(k)}(\\hat s)``, `k = 0,…,2order+1`, with ``K'(\\hat s)=\\bar x``.

* `pdf[M]`: Daniels expansion with the terms `m ≤ M-1` (relative error ``O(n^{-M})``);
* `cdf[M]`: Hauschildt-Robinson expansion of ``P(X ≤ \\bar x)`` with the terms `m ≤ 2M-1`;
* `upp[M]`: the same expansion of ``P(X > \\bar x)``, computed directly (use it for small upper
  tails);
* `kappa[M]`: cancellation indicator, (sum of |terms|)/|sum|.

Both signs of `shat` are handled (the reflection of Corollary 3). The "n" is absorbed in `K`.

The computation is generic in the floating-point type of the inputs. For `Float64` the integrals
``I_m(u)``, ``u=\\hat s K''(\\hat s)^{1/2}``, are generated by the forward recursion (39) for
`|u| ≤ uthr` and by 80-point Gauss-Hermite quadrature of a representation with positive
integrands otherwise. For other types (e.g. `BigFloat`) the forward recursion is used at every
`u`; it loses about ``\\log_{10}(u^{2m+1}/m!)`` digits at index `m`, so the precision must exceed
that loss by the accuracy wanted.
"""
function spa_uni(Kd::AbstractVector, shat::Real, xbar::Real, order::Integer; uthr::Real=2.5)
    order >= 1 || throw(ArgumentError("spa_uni: order must be a positive integer"))
    T = float(promote_type(eltype(Kd), typeof(shat), typeof(xbar)))
    Kd = T.(collect(Kd)); shat = T(shat); xbar = T(xbar)
    p = 2order - 1
    N = p + 2
    length(Kd) >= N + 1 || throw(ArgumentError("spa_uni: need K^(k) for k = 0..$N"))
    K2 = Kd[3]
    sK2 = sqrt(K2)
    theta = [Kd[k+1]/(factT(T, k)*sK2^k) for k in 3:N]      # theta[k-2] = theta_k
    J = N - 2
    d = dcoef(theta, J)
    h = hcoef(T, 2J)
    # Daniels density
    f0 = exp(Kd[1] - shat*xbar)/sqrt(2*T(pi)*K2)
    pdf = zeros(T, order)
    s = one(T)
    for M in 1:order
        M > 1 && (s += acoef(d, h, M-1, 2(M-1)))
        pdf[M] = f0*s
    end
    # Hauschildt-Robinson: R[m+1] = I_m(u)/phi(u) along the contour used (right of the pole for
    # shat >= 0, left of it for shat < 0); E*phi(u) = exp(K - shat*xbar)/sqrt(2 pi)
    u = shat*sK2
    Ephi = exp(Kd[1] - shat*xbar)/sqrt(2*T(pi))
    nI = 3p + 1
    if T !== Float64 || abs(u) <= uthr
        R = zeros(T, nI)
        R[1] = shat >= 0 ? normcdf(-u)/normpdf(u) : -normcdf(u)/normpdf(u)
        for i in 0:3p-1
            R[i+2] = iseven(i) ? h[i÷2+1] - u*R[i+1] : -u*R[i+1]
        end
    else
        R = Iherm(abs(u), nI - 1)
        if shat < 0
            for m in 0:nI-1
                R[m+1] = -(-1)^m*R[m+1]
            end
        end
    end
    cdf = zeros(T, order); upp = zeros(T, order); kappa = zeros(T, order)
    s = R[1]; sa = abs(R[1])
    m = 0
    for M in 1:order
        while m < 2M - 1
            m += 1
            for r in 1:m
                term = d[r, m]*R[m+2r+1]
                s += term; sa += abs(term)
            end
        end
        if shat >= 0
            upp[M] = Ephi*s; cdf[M] = 1 - upp[M]
        else
            cdf[M] = -Ephi*s; upp[M] = 1 - cdf[M]
        end
        kappa[M] = sa/abs(s)
    end
    return (; pdf, cdf, upp, kappa)
end

# R[m+1] = I_m(u)/phi(u), m = 0..mmax, u > 0: R[2k+1] = (-1)^k u M_k, R[2k+2] = (-1)^k M_{k+1},
# M_j = E[Z^(2j)/(u^2+Z^2)], Z ~ N(0,1), by 80-point Gauss-Hermite quadrature (positive terms).
function Iherm(u::Float64, mmax::Integer)
    xg, wg = gauher(80)
    q = wg ./ (u^2 .+ xg.^2); x2 = xg.^2
    J = mmax ÷ 2 + 1
    Mj = zeros(J + 1)
    for j in 0:J
        Mj[j+1] = sum(q); q = q .* x2
    end
    R = zeros(mmax + 1)
    for m in 0:mmax
        k = m ÷ 2
        R[m+1] = iseven(m) ? (-1)^k*u*Mj[k+1] : (-1)^k*Mj[k+2]
    end
    return R
end

"""
    spa_ratio_pdf(KWd, gd, shat, order) -> Vector

Rice (Laplace) expansion of orders `1:order` of
``(2\\pi i)^{-1}\\int \\exp\\{K_W(s)\\}g(s)\\,ds`` through the saddlepoint `shat` of ``K_W``
(``K_W'(\\hat s)=0``), Corollary 5 of the paper: `KWd[k+1]` = ``K_W^{(k)}(\\hat s)``,
`k = 0..2order`, and `gd[l+1]` = ``g^{(l)}(\\hat s)``, `l = 0..2order-2`. For the density of
``R=X/Y`` at `r`, with ``Y>0`` and joint cumulant generating function ``K(s,t)``, take
``K_W(s)=K(s,-rs)`` and ``g(s)=\\partial K(s,t)/\\partial t`` at ``t=-rs``.
"""
function spa_ratio_pdf(KWd::AbstractVector, gd::AbstractVector, shat::Real, order::Integer)
    order >= 1 || throw(ArgumentError("spa_ratio_pdf: order must be a positive integer"))
    length(KWd) >= 2order + 1 ||
        throw(ArgumentError("spa_ratio_pdf: need K_W^(k)(shat) for k = 0..$(2order) (got $(length(KWd)) values)"))
    length(gd) >= 2order - 1 ||
        throw(ArgumentError("spa_ratio_pdf: need g^(l)(shat) for l = 0..$(2order - 2) (got $(length(gd)) values)"))
    T = float(promote_type(eltype(KWd), eltype(gd), typeof(shat)))
    KWd = T.(collect(KWd)); gd = T.(collect(gd))
    N = 2order
    K2 = KWd[3]; sK2 = sqrt(K2)
    theta = [k + 1 <= length(KWd) ? KWd[k+1]/(factT(T, k)*sK2^k) : zero(T) for k in 3:N+2]
    J = N
    d = dcoef(theta, J)
    h = hcoef(T, 2J)
    g0 = gd[1]
    gam = zeros(T, N + 1)
    for l in 0:N-2
        gam[l+1] = gd[l+1]/(factT(T, l)*g0*sK2^l)
    end
    lead = exp(KWd[1])*g0/sqrt(2*T(pi)*K2)
    pdf = zeros(T, order)
    s = zero(T)
    for M in 1:order
        j = M - 1
        for kk in 0:2j
            s += gam[2j-kk+1]*acoef(d, h, j, kk)
        end
        pdf[M] = lead*s
    end
    return pdf
end
