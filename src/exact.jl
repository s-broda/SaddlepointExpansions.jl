# Exact values (double precision) against which the approximations are compared.

# Poisson(mu) weights above 1e-24 of the largest, mu = lam/2
function poisson_weights(lam::Real)
    mu = lam/2
    mu == 0 && return [0], [1.0]
    s = 15sqrt(mu + 1) + 25
    j = collect(max(0, floor(Int, mu - s)):ceil(Int, mu + s))
    w = exp.(-mu .+ j .* log(mu) .- loggamma.(j .+ 1.0))
    keep = w .>= 1e-24*maximum(w)
    return j[keep], w[keep]
end

"""
    ncx2_exact(x, nu, lam) -> (; cdf, upp, pdf)

Distribution function, upper tail and density of ``χ^2_ν(λ)`` at `x` in double precision, as
Poisson mixtures of central chi-squared values (both tails computed directly).
"""
function ncx2_exact(x::Real, nu::Real, lam::Real)
    x <= 0 && return (; cdf=0.0, upp=1.0, pdf=0.0)
    j, w = poisson_weights(lam)
    cdf = 0.0; upp = 0.0; pdf = 0.0
    for (jj, ww) in zip(j, w)
        a = nu/2 + jj
        P, Q = gamma_inc(a, x/2, 0)
        cdf += ww*P; upp += ww*Q
        pdf += ww*exp((a - 1)*log(x/2) - x/2 - loggamma(a))/2
    end
    return (; cdf, upp, pdf)
end

"""
    gamma_exact(x, a) -> (; cdf, upp, pdf)

Gamma distribution with shape `a` and unit scale.
"""
function gamma_exact(x::Real, a::Real)
    P, Q = gamma_inc(a, x, 0)
    return (; cdf=P, upp=Q, pdf=exp((a - 1)*log(x) - x - loggamma(a)))
end

"""
    dncf_exact_dp(f, m, n, lam1, lam2) -> (; cdf, upp, pdf)

Distribution function, upper tail and density of the doubly noncentral F in double precision:
double Poisson mixture of regularized incomplete beta functions ``I_x(a+j,b+k)``, ``a=m/2``,
``b=n/2``, ``x=c/(1+c)``, ``c=mf/n``, with the incomplete beta values generated by recurrences in
the additive direction, so that each output is a sum of positive terms. `lam2 = 0` gives the
singly noncentral F.
"""
function dncf_exact_dp(f::Real, m::Real, n::Real, lam1::Real, lam2::Real)
    c = m*f/n; x = c/(1 + c); y = 1/(1 + c); a = m/2; b = n/2; xy = x*y
    lx = log(x); ly = log(y)
    j, wj = poisson_weights(lam1); k, wk = poisson_weights(lam2)  # contiguous ranges
    aj = a .+ j; bk = b .+ k
    nj = length(aj); nk = length(bk)
    la = loggamma.(aj); lb = loggamma.(bk)
    lab = loggamma.(a + b + j[1] + k[1] .+ (0:nj+nk-2))           # loggamma(aj[p] + bk[q])
    # beta density terms P(p,q) = x^(aj-1) y^(bk-1)/B(aj,bk)
    P(p, q) = exp((aj[p] - 1)*lx + (bk[q] - 1)*ly + lab[p+q-1] - la[p] - lb[q])
    cdf = 0.0; upp = 0.0; pdf = 0.0
    # lower: I_x(aj[p], bk[q]); start at (aj[end], bk[1]), forward in b, down in a
    top = beta_inc(aj[nj], bk[1], x, y)[1]
    for q in 1:nk
        q > 1 && (top += P(nj, q - 1)*xy/bk[q-1])
        sI = top
        for p in nj:-1:1
            p < nj && (sI += P(p, q)*xy/aj[p])
            Ppq = P(p, q)
            W = wj[p]*wk[q]
            cdf += W*sI; pdf += W*Ppq
        end
    end
    # upper: I_y(bk[q], aj[p]); start at (bk[end], aj[1]), forward in a, down in b
    col = beta_inc(bk[nk], aj[1], y, x)[1]
    for p in 1:nj
        p > 1 && (col += P(p - 1, nk)*xy/aj[p-1])
        sI = col
        for q in nk:-1:1
            q < nk && (sI += P(p, q)*xy/bk[q])
            upp += wj[p]*wk[q]*sI
        end
    end
    return (; cdf, upp, pdf=pdf*(m/n)*y^2)
end

"""
    bqfcc_exact(x1, x2, m, lam) -> (; Fup, pdf, Flo)

``P(Q_1 ≥ x_1, Q_2 ≥ x_2)``, the joint density and ``P(Q_1 ≤ x_1, Q_2 ≤ x_2)`` for
``Q_1=X_1+X_0``, ``Q_2=X_2+X_0`` (`m = [m1, m2, m0]`, `lam = [lam1, lam2, lam0]`), by
one-dimensional adaptive integration over ``X_0`` in double precision (relative tolerance 1e-12).
"""
function bqfcc_exact(x1::Real, x2::Real, m, lam)
    f0(s) = ncx2_exact(s, m[3], lam[3]).pdf
    up(s, x, mm, ll) = s >= x ? 1.0 : ncx2_exact(x - s, mm, ll).upp
    lo(s, x, mm, ll) = s >= x ? 0.0 : ncx2_exact(x - s, mm, ll).cdf
    dn(s, x, mm, ll) = s >= x ? 0.0 : ncx2_exact(x - s, mm, ll).pdf
    xm = min(x1, x2)
    Fup = quadgk(s -> f0(s)*up(s, x1, m[1], lam[1])*up(s, x2, m[2], lam[2]), 0, xm, max(x1, x2), Inf;
                 rtol=1e-12)[1]
    Flo = quadgk(s -> f0(s)*lo(s, x1, m[1], lam[1])*lo(s, x2, m[2], lam[2]), 0, xm; rtol=1e-12)[1]
    pdf = quadgk(s -> f0(s)*dn(s, x1, m[1], lam[1])*dn(s, x2, m[2], lam[2]), 0, xm; rtol=1e-12)[1]
    return (; Fup, pdf, Flo)
end
